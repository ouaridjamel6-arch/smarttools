export const CalendarService = {
  getPosts(): CalendarPost[] {
    let posts = StorageService.getCalendarPosts();
    if (!posts || posts.length === 0) {
      posts = INITIAL_30_DAYS_POSTS;
      StorageService.saveCalendarPosts(posts);
    }
    return posts;
  },

  updatePostStatus(id: string, newStatus: PostStatus): void {
    const posts = this.getPosts().map((p) => (p.id === id ? { ...p, status: newStatus } : p));
    StorageService.saveCalendarPosts(posts);
  },

  updatePost(updated: CalendarPost): void {
    const posts = this.getPosts().map((p) => (p.id === updated.id ? updated : p));
    StorageService.saveCalendarPosts(posts);
  },

  addPost(post: Omit<CalendarPost, 'id'>): CalendarPost {
    const posts = this.getPosts();
    const newPost: CalendarPost = {
      ...post,
      id: 'cal_' + Date.now(),
    };
    posts.push(newPost);
    StorageService.saveCalendarPosts(posts);
    return newPost;
  },

  exportICS(): string {
    const posts = this.getPosts();
    const lines = [
      'BEGIN:VCALENDAR',
      'VERSION:2.0',
      'PRODID:-//SMARTTOOLS//Marketing Calendar 30 Days//EN',
      'CALSCALE:GREGORIAN',
      'METHOD:PUBLISH',
    ];

    posts.forEach((p) => {
      const dt = p.date.replace(/-/g, '');
      const timeClean = p.time.replace(':', '') + '00';
      const dtstart = `${dt}T${timeClean}Z`;
      const cleanSummary = p.topic.replace(/,/g, '\\,').replace(/;/g, '\\;');
      const cleanDesc = (p.content || '').replace(/\n/g, '\\n').replace(/,/g, '\\,');

      lines.push('BEGIN:VEVENT');
      lines.push(`UID:${p.id}@smarttools-um7.pages.dev`);
      lines.push(`DTSTAMP:${dtstart}`);
      lines.push(`DTSTART:${dtstart}`);
      lines.push(`SUMMARY:[${p.platform.toUpperCase()}] ${cleanSummary}`);
      lines.push(`DESCRIPTION:Language: ${p.language.toUpperCase()}\\nTool: ${p.toolId}\\nStatus: ${p.status}\\n\\n${cleanDesc}`);
      lines.push('STATUS:CONFIRMED');
      lines.push('END:VEVENT');
    });

    lines.push('END:VCALENDAR');
    return lines.join('\r\n');
  },
};
